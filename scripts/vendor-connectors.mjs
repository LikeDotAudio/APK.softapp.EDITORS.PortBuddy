/**
 * VENDOR THE CLOSED CONNECTOR VOCABULARY — contracts/ifc/connectors.json and its
 * resolver (contracts/src/ifc-vocab.ts: normaliseConnector, connectorById,
 * resolveConnector(s), portWords) bundled with esbuild into
 * vendor/apk-contracts/apk-connectors.js, one dependency-free ES module this app
 * loads with no build step. A port's connector is written as the canonical id's
 * ISO 16739 words (Pset_DistributionPortTypeCable), never a spelling of our own.
 *
 *   node scripts/vendor-connectors.mjs           write the bundle
 *   node scripts/vendor-connectors.mjs --check   exit 1 when the bundle is not what contracts builds to today
 *
 * Needs the monorepo checkout (../../../../../contracts with its node_modules);
 * on its own this repo keeps the committed bundle and the check says it skipped.
 * The same bytes in EDITORS.AdapterBuddy and EDITORS.PortBuddy.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const APP = resolve(HERE, '..');
export const CONTRACTS = resolve(APP, '../../../../../contracts');
export const BUNDLE = join(APP, 'vendor/apk-contracts/apk-connectors.js');
const NAMES = ['normaliseConnector', 'connectorById', 'resolveConnector', 'resolveConnectors', 'portWords', 'IFC_CONNECTORS'];

const HEADER =
  '/* Part of the APK.audio project — http://APK.audio — made by Anthony Kuzub\n' +
  '   MIT Licence. Free, for everyone, for ever. Full text in LICENSE at the root.\n' +
  '   GENERATED by scripts/vendor-connectors.mjs — DO NOT EDIT. Source: contracts/ifc/connectors.json\n' +
  '   + contracts/src/ifc-vocab.ts (the closed connector vocabulary and its resolver).\n' +
  '   Regenerate: node scripts/vendor-connectors.mjs */\n';

/** The bundle as contracts builds to today, or null when contracts (or its esbuild) is not here. */
export async function buildBundle() {
  const entry = join(CONTRACTS, 'src/ifc-vocab.ts');
  const esbuildPath = join(CONTRACTS, 'node_modules/esbuild');
  if (!existsSync(entry) || !existsSync(esbuildPath)) return null;
  const { build } = createRequire(join(CONTRACTS, 'package.json'))('esbuild');
  const out = await build({
    absWorkingDir: CONTRACTS,
    stdin: { contents: `export { ${NAMES.join(', ')} } from './src/ifc-vocab.ts'`, resolveDir: CONTRACTS, loader: 'ts', sourcefile: 'apk-connectors.ts' },
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2020',
    charset: 'utf8',
    legalComments: 'none',
    minifyWhitespace: true,
    minifySyntax: true,
    metafile: true,
    write: false,
  });
  const foreign = Object.keys(out.metafile.inputs).filter((p) => p.includes('node_modules'));
  if (foreign.length) throw new Error(`contracts/src/ifc-vocab.ts must stay dependency-free; it pulled in ${foreign.join(', ')}`);
  return HEADER + out.outputFiles[0].text;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = await buildBundle();
  if (text == null) {
    console.log('vendor-connectors: contracts/ is not beside this app — kept the committed bundle');
  } else if (process.argv.includes('--check')) {
    const now = existsSync(BUNDLE) ? readFileSync(BUNDLE, 'utf8') : '';
    if (now !== text) {
      console.error('vendor-connectors: vendor/apk-contracts/apk-connectors.js is stale — run node scripts/vendor-connectors.mjs');
      process.exit(1);
    }
    console.log('vendor-connectors: fresh');
  } else {
    writeFileSync(BUNDLE, text);
    console.log(`vendor-connectors: wrote ${BUNDLE} (${text.length} bytes)`);
  }
}
